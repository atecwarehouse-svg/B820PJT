/** Excel 날짜 직렬값 → 글자색(ARGB): 일요일·공휴일 빨강, 토요일 파랑, 평일 검정 */
export function dateFontColor(serial: number): string {
  const d = new Date(Date.UTC(1899, 11, 30) + serial * 86400000);
  const day = d.getUTCDay();
  if (day === 0 || KR_HOLIDAYS.has(d.toISOString().slice(0, 10))) return "FFFF0000";
  if (day === 6) return "FF0000FF";
  return "FF000000";
}
